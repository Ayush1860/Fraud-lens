"""Write ``report.md`` and its figures from the training artefacts.

Every number in the report is read from a JSON artefact; nothing is typed by hand.
"""

import json
import os
from collections.abc import Mapping
from pathlib import Path
from types import ModuleType
from typing import Any

BLUE, ORANGE = "#2a78d6", "#eb6834"
ARM_COLOURS = ("#52514e", "#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#6250d6")


def _pyplot() -> ModuleType:
    """Import pyplot drawing to files only, whatever backend the environment requests.

    Jupyter and Colab export ``MPLBACKEND=module://matplotlib_inline.backend_inline`` to
    every shell command. The project environment does not install that backend, and
    matplotlib rejects the setting at import time, so it is replaced before importing.
    """
    os.environ["MPLBACKEND"] = "Agg"
    import matplotlib

    matplotlib.use("Agg", force=True)
    import matplotlib.pyplot as plt

    return plt


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _metric(summary: Mapping[str, Any], name: str, digits: int = 3) -> str:
    entry = summary.get(name)
    if entry is None or entry["mean"] is None:
        return "n/a"
    text = f"{entry['mean']:.{digits}f}"
    if entry.get("ci95"):
        low, high = entry["ci95"]
        text += f" [{low:.{digits}f}, {high:.{digits}f}]"
    return text


def _arm_table(study: Mapping[str, Any]) -> list[str]:
    lines = [
        "| Arm | Setup | Average precision | Recall @ 1% | Dollar recall @ 1% "
        "| Precision @ 1% | Brier | ROC-AUC |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for arm in study["arms"]:
        s = arm["summary"]
        lines.append(
            f"| {arm['arm']} | {arm['description']} | {_metric(s, 'average_precision')} "
            f"| {_metric(s, 'recall_at_1pct')} | {_metric(s, 'dollar_recall_at_1pct')} "
            f"| {_metric(s, 'precision_at_1pct')} | {_metric(s, 'brier', 5)} "
            f"| {s['roc_auc']['mean']:.4f} |"
        )
    return lines


def _pr_figure(study: Mapping[str, Any], path: Path, title: str) -> None:
    plt = _pyplot()
    fig, ax = plt.subplots(figsize=(7, 4.5))
    for colour, arm in zip(ARM_COLOURS, study["arms"], strict=False):
        curve = arm["pr_curve"]
        ax.plot(curve["recall"], curve["precision"], color=colour, linewidth=2, label=arm["arm"])
    ax.set_xlabel("Recall")
    ax.set_ylabel("Precision")
    ax.set_title(title, loc="left", fontweight="bold")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1.02)
    ax.grid(color="#e8e7e2")
    ax.legend(frameon=False, ncols=4)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def _reliability_figure(test: Mapping[str, Any], path: Path) -> None:
    plt = _pyplot()
    fig, ax = plt.subplots(figsize=(5.5, 5))
    ax.plot([1e-5, 1], [1e-5, 1], color="#c9c8c2", linewidth=1, label="Perfect calibration")
    for key, colour, name in (
        ("reliability_raw", ORANGE, "Before calibration"),
        ("reliability_calibrated", BLUE, "After isotonic calibration"),
    ):
        points = [p for p in test[key] if p["observed"] > 0 and p["mean_predicted"] > 0]
        ax.plot(
            [p["mean_predicted"] for p in points],
            [p["observed"] for p in points],
            color=colour,
            linewidth=2,
            marker="o",
            label=name,
        )
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Mean predicted probability")
    ax.set_ylabel("Observed fraud rate")
    ax.set_title("Reliability on the test set", loc="left", fontweight="bold")
    ax.grid(color="#e8e7e2")
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def write_report(results_dir: Path, bundle_dir: Path | None) -> Path:
    """Assemble ``results_dir/report.md`` from whatever artefacts exist.

    Reads ``experiments.json``, ``tuning.json`` and ``ulb.json`` from ``results_dir`` and
    ``metrics.json``, ``training.json`` and ``test_metrics.json`` from the bundle.
    """
    figures = results_dir / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    study = _load(results_dir / "experiments.json")
    tuning = _load(results_dir / "tuning.json")
    ulb = _load(results_dir / "ulb.json")
    bundle_docs: dict[str, Any] = {}
    if bundle_dir is not None:
        for name in ("metrics.json", "training.json", "test_metrics.json", "thresholds.json"):
            bundle_docs[name] = _load(bundle_dir / name)

    lines = [
        "# FraudLens model report",
        "",
        "Generated by `python -m fraudlens.training report` from the JSON artefacts in this "
        "directory and in the model bundle. Intervals are 95% day-block bootstrap intervals.",
        "",
        "> **Simulated data.** Sparkov is generated data; these numbers show method, not "
        "real-world accuracy.",
        "",
    ]

    if study:
        lines += [
            "## Imbalance study",
            "",
            f"Seven arms, {len(study['seeds'])} seeds each, trained on {study['train_rows']:,} "
            f"rows ({study['train_frauds']:,} frauds) and evaluated on the early validation "
            f"slice: {study['eval_rows']:,} rows, {study['eval_frauds']:,} frauds. "
            "Each value is the mean over seeds. Brier scores are on the arm's own "
            "probabilities, before any calibration.",
            "",
            *_arm_table(study),
            "",
            "![Precision-recall by arm](figures/pr_curves.png)",
            "",
        ]
        _pr_figure(study, figures / "pr_curves.png", "Precision-recall, early validation")

    if tuning:
        lines += [
            "## Tuning",
            "",
            f"Arm {tuning['arm']}, {tuning['n_trials']} Optuna trials, objective: "
            f"{tuning['objective']}. Best value: {tuning['best_value']:.4f}.",
            "",
            "```json",
            json.dumps(tuning["best_params"], indent=2, sort_keys=True),
            "```",
            "",
        ]

    training = bundle_docs.get("training.json")
    metrics = bundle_docs.get("metrics.json")
    if training and metrics and bundle_dir is not None:
        late = metrics["valid_late"]
        thresholds = bundle_docs["thresholds.json"]
        lines += [
            f"## Release {bundle_dir.name}",
            "",
            f"Arm {training['arm']}, {training['best_iteration'] + 1} trees, git commit "
            f"`{training['git_commit'][:12]}`.",
            "",
            f"- Thresholds, chosen on the late validation slice: review at "
            f"{thresholds['t_review']:.4f}, block at {thresholds['t_block']:.4f}.",
            f"- Brier score on the late validation slice: {late['brier_raw']:.5f} raw, "
            f"{late['brier_calibrated']:.5f} calibrated (in-sample for the calibrator).",
            "",
        ]

    test = bundle_docs.get("test_metrics.json")
    if test:
        ranking = test["ranking"]
        lines += [
            "## Final test",
            "",
            f"Scored once: {test['rows']:,} transactions over {test['days']} days, "
            f"{test['frauds']:,} frauds.",
            "",
            "| Metric | Value |",
            "| --- | --- |",
            f"| Average precision | {_metric(ranking, 'average_precision')} |",
            f"| Recall @ 0.5% daily budget | {_metric(ranking, 'recall_at_0_5pct')} |",
            f"| Recall @ 1% daily budget | {_metric(ranking, 'recall_at_1pct')} |",
            f"| Dollar recall @ 1% daily budget | {_metric(ranking, 'dollar_recall_at_1pct')} |",
            f"| Precision @ 1% daily budget | {_metric(ranking, 'precision_at_1pct')} |",
            f"| ROC-AUC (reported, not optimised) | {ranking['roc_auc']['mean']:.4f} |",
            f"| Brier score, raw / calibrated | {test['brier_raw']:.5f} / "
            f"{test['brier_calibrated']:.5f} |",
            f"| Expected cost per 1,000 transactions | ${test['expected_cost_per_1000']:.2f} |",
            f"| Cost per 1,000 if everything were approved | "
            f"${test['cost_of_approving_everything_per_1000']:.2f} |",
            "",
            "![Reliability before and after calibration](figures/reliability_test.png)",
            "",
            "### Review queue order",
            "",
            "| Budget | Ordering | Recall | Dollar recall | Precision |",
            "| --- | --- | --- | --- | --- |",
        ]
        for budget, orderings in test["queue_ordering"].items():
            for ordering, values in orderings.items():
                lines.append(
                    f"| {budget.replace('_', '.')} | {ordering.replace('_', ' ')} "
                    f"| {values['recall']:.3f} | {values['dollar_recall']:.3f} "
                    f"| {values['precision']:.3f} |"
                )
        lines += [
            "",
            "### Fairness check",
            "",
            "False-positive rate of any flag (review or block) among genuine transactions. "
            "The model never sees gender; age enters only as a feature.",
            "",
            "| Group | Genuine rows | False-positive rate | Recall |",
            "| --- | --- | --- | --- |",
        ]
        for kind in ("gender", "age_band"):
            for row in test["fairness"][kind]:
                fpr = row["false_positive_rate"]
                recall = row["recall"]
                lines.append(
                    f"| {row['group']} | {row['genuine_rows']:,} "
                    f"| {'n/a' if fpr is None else f'{fpr:.4%}'} "
                    f"| {'n/a' if recall is None else f'{recall:.3f}'} |"
                )
        lines.append("")
        _reliability_figure(test, figures / "reliability_test.png")

    if ulb:
        lines += [
            "## ULB benchmark",
            "",
            f"The same harness on the ULB dataset: {ulb['train_rows']:,} training rows, "
            f"{ulb['eval_rows']:,} evaluation rows ({ulb['eval_frauds']} frauds), split by "
            "time. Budgets are per hour.",
            "",
            *_arm_table(ulb),
            "",
        ]

    path = results_dir / "report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
